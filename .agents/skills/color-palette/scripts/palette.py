#!/usr/bin/env python3
"""Deterministic Quail color-palette token generation and WCAG checks."""

from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

PALETTE = {
    "brand-blue": "#4392F1",
    "neutral-lavender": "#ECE8EF",
    "surface-blue-soft": "#E3EBFF",
    "surface-blue-pale": "#E7F0FF",
    "error-red": "#DC493A",
}

# Dark foreground is used for normal text on saturated brand/error colors because
# white does not reach WCAG AA (4.5:1) for normal text on those colors.
DARK_FOREGROUND = "#0B1120"
LIGHT_FOREGROUND = "#FFFFFF"

CONTRAST_PAIRS = [
    ("--color-brand", "--color-on-brand", 4.5),
    ("--color-error", "--color-on-error", 4.5),
    ("--color-surface", "--color-on-surface", 4.5),
    ("--color-surface-brand", "--color-on-surface-brand", 4.5),
    ("--color-surface-brand-soft", "--color-on-surface-brand-soft", 4.5),
]


def hex_to_rgb(value: str) -> tuple[int, int, int]:
    value = value.strip().lstrip("#")
    if len(value) != 6 or not re.fullmatch(r"[0-9a-fA-F]{6}", value):
        raise ValueError(f"invalid hex color: {value!r}")
    return int(value[0:2], 16), int(value[2:4], 16), int(value[4:6], 16)


def relative_luminance(color: str) -> float:
    def channel(value: int) -> float:
        normalized = value / 255
        if normalized <= 0.03928:
            return normalized / 12.92
        return ((normalized + 0.055) / 1.055) ** 2.4

    red, green, blue = hex_to_rgb(color)
    return 0.2126 * channel(red) + 0.7152 * channel(green) + 0.0722 * channel(blue)


def contrast_ratio(foreground: str, background: str) -> float:
    foreground_luminance = relative_luminance(foreground)
    background_luminance = relative_luminance(background)
    lighter = max(foreground_luminance, background_luminance)
    darker = min(foreground_luminance, background_luminance)
    return (lighter + 0.05) / (darker + 0.05)


def token_values() -> dict[str, str]:
    return {
        "--color-brand": PALETTE["brand-blue"],
        "--color-on-brand": DARK_FOREGROUND,
        "--color-surface": PALETTE["neutral-lavender"],
        "--color-on-surface": DARK_FOREGROUND,
        "--color-surface-brand": PALETTE["surface-blue-soft"],
        "--color-on-surface-brand": DARK_FOREGROUND,
        "--color-surface-brand-soft": PALETTE["surface-blue-pale"],
        "--color-on-surface-brand-soft": DARK_FOREGROUND,
        "--color-error": PALETTE["error-red"],
        "--color-on-error": DARK_FOREGROUND,
        "--color-border": PALETTE["brand-blue"],
        "--color-focus": PALETTE["brand-blue"],
    }


def spacing_tokens() -> dict[str, str]:
    return {
        "--space-1": "0.25rem",
        "--space-2": "0.5rem",
        "--space-3": "0.75rem",
        "--space-4": "1rem",
        "--space-6": "1.5rem",
        "--space-8": "2rem",
        "--radius-sm": "0.375rem",
        "--radius-md": "0.75rem",
        "--radius-lg": "1rem",
    }


def css_tokens() -> str:
    tokens = {**token_values(), **spacing_tokens()}
    lines = [
        "/* Generated by .agents/skills/color-palette/scripts/palette.py. Do not edit by hand. */",
        ":root {",
    ]
    for name, value in tokens.items():
        lines.append(f"  {name}: {value};")
    lines.extend(
        [
            "}",
            "",
            "/* Contrast notes (WCAG 2.1, normal text requires 4.5:1):",
        ]
    )
    for background_name, foreground_name, threshold in CONTRAST_PAIRS:
        background = tokens[background_name]
        foreground = tokens[foreground_name]
        ratio = contrast_ratio(foreground, background)
        status = "pass" if ratio >= threshold else "FAIL"
        lines.append(
            f"  {foreground_name} on {background_name}: {ratio:.2f}:1 ({status}, threshold {threshold:.1f}:1)"
        )
    # Document the explicitly requested blue/white check.
    blue_white = contrast_ratio(LIGHT_FOREGROUND, PALETTE["brand-blue"])
    lines.append(
        f"  --color-on-brand candidate #FFFFFF on brand blue: {blue_white:.2f}:1 "
        f"({'pass' if blue_white >= 4.5 else 'FAIL, so normal text uses dark foreground'})"
    )
    red_white = contrast_ratio(LIGHT_FOREGROUND, PALETTE["error-red"])
    lines.append(
        f"  --color-on-error candidate #FFFFFF on error red: {red_white:.2f}:1 "
        f"({'pass' if red_white >= 4.5 else 'FAIL, so normal text uses dark foreground'})"
    )
    lines.append("*/")
    lines.append("")
    return "\n".join(lines)


def generate(output: Path) -> Path:
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(css_tokens(), encoding="utf-8", newline="\n")
    return output


def parse_css_variables(text: str) -> dict[str, str]:
    variables: dict[str, str] = {}
    for match in re.finditer(r"(--[a-zA-Z0-9-]+)\s*:\s*([^;]+);", text):
        variables[match.group(1)] = match.group(2).strip()
    return variables


def check(text: str) -> list[str]:
    errors: list[str] = []
    variables = parse_css_variables(text)

    for name, expected in token_values().items():
        if variables.get(name) != expected:
            errors.append(f"missing or wrong token {name}: expected {expected}, got {variables.get(name)!r}")

    for background_name, foreground_name, threshold in CONTRAST_PAIRS:
        background = variables.get(background_name)
        foreground = variables.get(foreground_name)
        if not background or not foreground:
            errors.append(f"cannot check contrast for {foreground_name} on {background_name}: missing token")
            continue
        ratio = contrast_ratio(foreground, background)
        if ratio < threshold:
            errors.append(
                f"contrast failure: {foreground_name} on {background_name} is {ratio:.2f}:1, need {threshold:.1f}:1"
            )

    # The requested palette must remain present even if tokens are renamed later.
    for name, value in PALETTE.items():
        if value.lower() not in text.lower():
            errors.append(f"palette color {name} ({value}) is missing from CSS")

    return errors


def command_generate(args: argparse.Namespace) -> int:
    output = generate(Path(args.output))
    print(f"Generated {output}")
    return 0


def command_check(args: argparse.Namespace) -> int:
    path = Path(args.input)
    text = path.read_text(encoding="utf-8")
    errors = check(text)
    if errors:
        for error in errors:
            print(f"FAIL: {error}", file=sys.stderr)
        return 1
    print(f"OK: {path} passes palette and contrast checks")
    return 0


def command_contrast(args: argparse.Namespace) -> int:
    ratio = contrast_ratio(args.foreground, args.background)
    print(f"{ratio:.2f}:1")
    return 0


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    subparsers = parser.add_subparsers(dest="command", required=True)

    generate_parser = subparsers.add_parser("generate", help="generate assets/palette.css")
    generate_parser.add_argument("--output", default=".agents/skills/color-palette/assets/palette.css")
    generate_parser.set_defaults(func=command_generate)

    check_parser = subparsers.add_parser("check", help="validate a generated palette CSS file")
    check_parser.add_argument("--input", required=True)
    check_parser.set_defaults(func=command_check)

    contrast_parser = subparsers.add_parser("contrast", help="compute a WCAG contrast ratio")
    contrast_parser.add_argument("foreground")
    contrast_parser.add_argument("background")
    contrast_parser.set_defaults(func=command_contrast)

    args = parser.parse_args()
    return args.func(args)


if __name__ == "__main__":
    raise SystemExit(main())